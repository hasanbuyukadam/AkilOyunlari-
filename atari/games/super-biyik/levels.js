export const ROWS = 15;

// Parçaları birleştirip 15 satırlık karakter ızgarası üretir.
export function buildArea(chunks) {
  const rows = Array.from({ length: ROWS }, () => []);
  for (const ch of chunks) {
    const w = Math.max(...ch.map((r) => r.length));
    const off = ROWS - ch.length;
    for (let y = 0; y < ROWS; y++) {
      const src = y >= off ? ch[y - off] : '';
      for (let x = 0; x < w; x++) rows[y].push(src[x] || '.');
    }
  }
  return rows;
}
