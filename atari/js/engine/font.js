// Aksanlı harfler: taban harf + üstte (y-2) veya altta (y+7) tek satır işaret.
const COMPOSE = {
  'Ç': ['C', null, '00100'],
  'Ş': ['S', null, '00100'],
  'Ğ': ['G', '01110', null],
  'Ö': ['O', '01010', null],
  'Ü': ['U', '01010', null],
  'İ': ['I', '00100', null],
};

const parse = (s) => s.split(' ').map((r) => [...r].map((c) => c === '1'));
const GLYPHS = {};
for (const [ch, s] of Object.entries(G)) GLYPHS[ch] = { rows: parse(s) };
for (const [ch, [base, above, below]] of Object.entries(COMPOSE)) {
  GLYPHS[ch] = {
    rows: GLYPHS[base].rows,
    above: above && parse(above)[0],
    below: below && parse(below)[0],
  };
}

export const CHAR_W = 6; // 5 piksel + 1 boşluk
export const CHAR_H = 7;

export function normalize(str) {
  return String(str).toLocaleUpperCase('tr-TR');
}

export function textWidth(str, scale = 1) {
  const n = [...normalize(str)].length;
  return n ? (n * CHAR_W - 1) * scale : 0;
}

// Metni ctx üzerine piksel piksel çizer (tek path + tek fill).
export function drawText(ctx, str, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  ctx.beginPath();
  let cx = Math.round(x);
  y = Math.round(y);
  for (const ch of normalize(str)) {
    const g = GLYPHS[ch] || GLYPHS['?'];
    g.rows.forEach((row, ry) => row.forEach((on, rx) => {
      if (on) ctx.rect(cx + rx * scale, y + ry * scale, scale, scale);
    }));
    if (g.above) g.above.forEach((on, rx) => on && ctx.rect(cx + rx * scale, y - 2 * scale, scale, scale));
    if (g.below) g.below.forEach((on, rx) => on && ctx.rect(cx + rx * scale, y + 7 * scale, scale, scale));
    cx += CHAR_W * scale;
  }
  ctx.fill();
}
